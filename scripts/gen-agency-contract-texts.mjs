// Copies the portal's contract texts (agencyPortal.contract.*) from locales into the agency-hub edge
// function, so the agreement PDF says exactly what the portal says. Run after editing those keys.
import { readFileSync, writeFileSync } from 'node:fs';
const keys = ['c1t', 'c1', 'c2t', 'c2', 'c3t', 'c3', 'c4t', 'c4', 'c5t', 'c5', 'you', 'us'];
const out = {};
for (const l of ['es', 'en', 'ro', 'id']) {
  const c = JSON.parse(readFileSync(new URL(`../locales/${l}.json`, import.meta.url))).agencyPortal.contract;
  out[l] = Object.fromEntries(keys.map((k) => [k, c[k]]));
}
writeFileSync(new URL('../supabase/functions/agency-hub/contract_texts.ts', import.meta.url),
  `// @ts-nocheck — GENERATED by scripts/gen-agency-contract-texts.mjs from locales/*.json (agencyPortal.contract). Do not edit.\nexport const C = ${JSON.stringify(out, null, 2)};\n`);
console.log('contract_texts.ts written');
